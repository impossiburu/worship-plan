/*
=====================================================
Генерация ID для элементов

Потом пригодится для сортировки
=====================================================
*/

function generateId(){
    return crypto.randomUUID ? crypto.randomUUID() : Date.now().toString(36) + Math.random().toString(36).slice(2);
}

/*
=====================================================
Создание пункта
=====================================================
*/

function createItem(){
    return {
        id: generateId(),
        type:"item",
        text:"",
        note:"",
        bold:false
    };
}

/*
=====================================================
Создание гимна
=====================================================
*/

function createHymn(){
    return {
        id: generateId(),
        type:"hymn",
        hymn:""
    };
}
